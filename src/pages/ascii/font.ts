/** Parsed glyphs: char → 7 rows of booleans (5 wide). */
export const FONT: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(RAW).map(([char, art]) => [
    char,
    art
      .replace(/^\n/, '')
      .split('\n')
      .map((row) => row.padEnd(GLYPH_WIDTH, '.').slice(0, GLYPH_WIDTH).split('').map((c) => c === '#')),
  ]),
);

const FALLBACK = FONT['?'];

/** Glyph bitmap for a character, upper-cased, falling back to `?`. */
export function glyphFor(char: string): boolean[][] {
  return FONT[char.toUpperCase()] ?? FONT[char] ?? FALLBACK;
}
